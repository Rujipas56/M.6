<?php
// กำหนดตัวแปรเงินของนายสมชาย
$money = 700; // คุณสามารถเปลี่ยนค่านี้เพื่อทดสอบเงื่อนไขต่างๆ ได้

// ตรวจสอบเงื่อนไขด้วย if, elseif, else
if ($money < 500) {
    echo "เขาสามารถซื้อกางเกงได้";
} elseif ($money < 1000) {
    echo "เขาสามารถซื้อกางเกงและเสื้อได้";
} elseif ($money < 1500) {
    echo "เขาสามารถซื้อกางเกง เสื้อ และรองเท้าได้";
} else {
    echo "เขามีเงินเพียงพอสำหรับซื้อสินค้าทุกอย่าง";
}
?>
