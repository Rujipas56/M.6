<?php
$students = ["นายรุจิภาส แสงอ่อง", "นายทุงทุง ซาโฮว", "นายตาราเรโร ตาลาลา", "นางบาเรรีนา คาปูชีนา"];
$i = 0; // ดัชนีเริ่มต้นของ Array

echo "--- รายชื่อนักเรียนห้อง 6/8 (while) ---\n";
while ($i < count($students)) {
    $no = $i + 1; // ให้ตัวนักเรียนเริ่มต้นที่เลขที่ 1
    echo "เลขที่ " . $no . ": " . $students[$i] . "\n";
    $i++; // เพิ่มค่าดัชนีเพื่อไปยังนักเรียนคนถัดไป
}
?>
